#!/usr/bin/env node
/**
 * Regenerates `src/renderers/design/defaults.ts` from the repository
 * `design/` sources. Run after intentionally evolving the design kit:
 *
 *   node scripts/embed-design-defaults.mjs
 *
 * The defaults exist so `docs init` can materialize an initial design
 * directory (create-missing-only) in new projects. Existing design
 * sources are never overwritten by init — edit `design/` directly.
 */
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const packageRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const designDir = join(packageRoot, "design");
const outFile = join(packageRoot, "src", "renderers", "design", "defaults.ts");

const files = ["tokens.css", "base.css", "components.css", "README.md"];
const keys = {
  "tokens.css": "Tokens",
  "base.css": "Base",
  "components.css": "Components",
  "README.md": "Readme",
};

let out = `/**
 * Embedded default design sources for @vetwo/docs.
 *
 * These templates mirror the VeTwo design system (design/tokens.css,
 * design/base.css, design/components.css, design/README.md). docs init
 * writes them once (create-missing-only); after that the design
 * directory is user-owned and builds only read from it.
 *
 * Generated by scripts/embed-design-defaults.mjs — keep in sync with
 * the repository design/ sources.
 */

export interface DesignSourceTemplate {
  readonly path:
    | "design/tokens.css"
    | "design/base.css"
    | "design/components.css"
    | "design/README.md";
  readonly contents: string;
}
`;

for (const file of files) {
  const contents = readFileSync(join(designDir, file), "utf8");
  out += `\nexport const defaultDesign${keys[file]} = ${JSON.stringify(contents)};\n`;
}

out += `
/** Embedded design kit: the four source files in canonical load order. */
export const DESIGN_SOURCE_TEMPLATES: readonly DesignSourceTemplate[] = [
  { path: "design/tokens.css", contents: defaultDesignTokens },
  { path: "design/base.css", contents: defaultDesignBase },
  { path: "design/components.css", contents: defaultDesignComponents },
  { path: "design/README.md", contents: defaultDesignReadme },
];
`;

mkdirSync(dirname(outFile), { recursive: true });
writeFileSync(outFile, out);
console.log(`Wrote ${outFile} from ${designDir}`);
