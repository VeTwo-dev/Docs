/**
 * Fumadocs Renderer (Phase 23) — the single primary internal Next.js
 * documentation renderer.
 *
 * Owns the `site/` output root exclusively: a REAL Fumadocs + Next.js project
 * whose content (`content/docs/*.mdx` + `meta.json`) is compiled from the
 * Documentation IR. The IR remains the semantic contract; Fumadocs owns all
 * page runtime, navigation UI, search UI, theming and routing.
 */

import type { DocumentationIR, IRBlock } from "../../documentation/compiler/ir.js";
import type { RenderedFile, RenderedSite, SiteRenderer, SiteRendererOptions } from "../types.js";
import {
  buildOutputPlan,
  planRoutes,
  rewriteBlockLinks,
  type DocumentationOutputPlan,
  type PlannedPage,
} from "../output-plan.js";
import { serializeBlock, serializeFrontmatter } from "../mdx.js";
import { renderCustomMarkdown, KNOWN_API_COMPONENTS } from "../api-markdown.js";
import { generateFumadocsScaffold, type FumadocsScaffoldInput } from "./scaffold.js";
import { buildGraphData, type GraphData } from "./graph.js";

// Re-exported for back-compat (public barrel + tests import from here).
export { renderCustomMarkdown } from "../api-markdown.js";

export type FumadocsRendererOptions = SiteRendererOptions;

/** A Fumadocs meta.json navigation file. */
interface MetaJson {
  readonly title?: string;
  readonly pages: readonly string[];
}

export function createFumadocsRenderer(): SiteRenderer<FumadocsRendererOptions> {
  return {
    target: "fumadocs",
    render(ir, options = {}) {
      return renderFumadocsSite(ir, options);
    },
  };
}

// Custom API blocks (`ApiSignature`, `ParameterTable`, …) are transformed to
// plain Markdown by `renderCustomMarkdown` (see `../api-markdown.js`, shared
// with the Markdown renderer's `.md` mode); re-exported above for back-compat.

function pageMarkdown(page: PlannedPage, plan: DocumentationOutputPlan): string {
  // Frontmatter stays first (required position) with a machine-readable
  // generator field; the ownership marker follows as `{/* */}` — the only
  // comment syntax valid inside MDX bodies.
  const frontmatter = serializeFrontmatter({
    title: page.title,
    description: page.page.description ?? "",
    generator: "@vetwo/docs",
  });
  const ownership = "{/* generated by @vetwo/docs — do not edit */}";
  // Skip the leading H1/summary: Fumadocs renders title + description itself.
  let blocks = page.page.blocks;
  if (blocks[0]?.kind === "heading" && blocks[0].level === 1 && blocks[0].text === page.title) {
    blocks = blocks.slice(1);
    if (
      page.page.description !== undefined &&
      blocks[0]?.kind === "paragraph" &&
      blocks[0].text === page.page.description
    ) {
      blocks = blocks.slice(1);
    }
  }
  // Authored relative links resolve to Fumadocs routes (`/api/overview`).
  const linked = rewriteBlockLinks(blocks, plan, page.slug, "fumadocs");
  return [frontmatter, ownership, "", toFumadocsMarkdown(linked), ""].join("\n");
}

/** Serialize blocks, routing custom API blocks through the Fumadocs transform. */
export function toFumadocsMarkdown(blocks: readonly IRBlock[]): string {
  return blocks
    .map((block) => {
      if (block.kind === "custom") {
        // Known API components degrade to portable Markdown; user MDX
        // components pass through as sanitized JSX (same as `.mdx` mode).
        if (!KNOWN_API_COMPONENTS.has(block.component)) return serializeBlock(block);
        return renderCustomMarkdown(
          block.component,
          (block.props ?? {}) as Record<string, unknown>,
        );
      }
      return serializeBlock(block);
    })
    .filter((s) => s.trim().length > 0)
    .join("\n\n");
}

/** Build folder meta.json navigation from the output plan. */
function buildMetaFiles(
  pages: readonly PlannedPage[],
  navigation: readonly {
    label: string;
    children?: readonly { label: string; slug?: string }[];
  }[],
): { path: string; contents: string }[] {
  const files: { path: string; contents: string }[] = [];
  const byDir = new Map<string, PlannedPage[]>();
  for (const page of pages) {
    const dir = page.slug.includes("/") ? page.slug.slice(0, page.slug.lastIndexOf("/")) : "";
    const arr = byDir.get(dir) ?? [];
    arr.push(page);
    byDir.set(dir, arr);
  }
  const rootOrder: string[] = [];
  for (const node of navigation) {
    for (const child of node.children ?? []) {
      if (child.slug !== undefined && !child.slug.includes("/")) rootOrder.push(child.slug);
    }
  }
  for (const page of pages) {
    if (!page.slug.includes("/") && !rootOrder.includes(page.slug)) rootOrder.push(page.slug);
  }
  const rootMeta: MetaJson = {
    pages: [...new Set([...rootOrder, ...[...byDir.keys()].filter((d) => d.length > 0)])],
  };
  files.push({
    path: "content/docs/meta.json",
    contents: `${JSON.stringify(rootMeta, null, 2)}\n`,
  });
  for (const [dir, members] of byDir) {
    if (dir.length === 0) continue;
    const meta: MetaJson = {
      title: dir
        .split("/")
        .map((s) => s.charAt(0).toUpperCase() + s.slice(1))
        .join(" / "),
      pages: members.map((p) => p.slug.slice(dir.length + 1)),
    };
    files.push({
      path: `content/docs/${dir}/meta.json`,
      contents: `${JSON.stringify(meta, null, 2)}\n`,
    });
  }
  return files;
}

/** Pure IR → Fumadocs project transformation. */
export function renderFumadocsSite(
  ir: DocumentationIR,
  options: FumadocsRendererOptions = {},
): RenderedSite {
  const siteName = options.siteName ?? "Documentation";
  const plan = buildOutputPlan(ir, {
    workspaceRoot: "",
    docsBasePath: options.docsBasePath ?? "/",
  });

  const scaffoldInput: FumadocsScaffoldInput = {
    siteName,
    description: options.description,
    baseUrl: options.baseUrl,
    theme: options.theme,
    navLinks: options.navLinks,
    logoSvg: options.logoSvg,
    designCss: options.designCss,
    // `/` serves the `index` document natively; without one, redirect root
    // to the deterministic plan home so the Home route always resolves.
    ...(plan.homeSlug !== undefined && plan.homeSlug !== "index"
      ? { homeRedirect: `/${plan.homeSlug}` }
      : {}),
  };

  const files: RenderedFile[] = [...generateFumadocsScaffold(scaffoldInput)];

  for (const planned of plan.pages) {
    files.push({
      path: `content/docs/${planned.slug}.mdx`,
      contents: pageMarkdown(planned, plan),
    });
  }
  for (const meta of buildMetaFiles(plan.pages, plan.navigation)) {
    files.push(meta);
  }

  const graph: GraphData = buildGraphData(ir);
  files.push({
    path: "public/graph.json",
    contents: `${JSON.stringify(graph, null, 2)}\n`,
  });

  return {
    target: "fumadocs",
    files,
    routes: planRoutes(plan),
    entrypoint: "app/layout.tsx",
  };
}
